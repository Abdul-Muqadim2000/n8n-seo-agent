import { describe, expect, it } from 'vitest';
import { crc32, readZip, rebrandDocument, writeZip } from '../src/services/docRebrand';
import { rewriteShell } from '../src/services/portalShell';

// G5 (WHITE_LABEL.md §6, §2): documents rewritten for a white-label client, and the page shell a portal host serves.

const docx = () =>
  writeZip([
    { name: '[Content_Types].xml', data: Buffer.from('<?xml version="1.0"?><Types/>') },
    { name: 'word/document.xml', data: Buffer.from('<w:document><w:t>Prepared by Dev SEO</w:t><w:t>Alaventra report</w:t></w:document>') },
    { name: 'word/footer1.xml', data: Buffer.from('<w:ftr><w:t>dev seo · page 1</w:t></w:ftr>') },
    { name: 'word/media/image1.png', data: Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x44, 0x65, 0x76]) },
  ]);

describe('zip', () => {
  it('crc32 matches the standard check value', () => {
    expect(crc32(Buffer.from('123456789'))).toBe(0xcbf43926);
  });
  it('round-trips entries', () => {
    const e = readZip(docx())!;
    expect(e.map((x) => x.name)).toEqual(['[Content_Types].xml', 'word/document.xml', 'word/footer1.xml', 'word/media/image1.png']);
    expect(e[1]!.data.toString()).toContain('Prepared by Dev SEO');
  });
  it('refuses what it does not handle', () => {
    expect(readZip(Buffer.from('not a zip at all'))).toBeNull();
    const z = docx();
    z.writeUInt16LE(1, z.indexOf(Buffer.from([0x50, 0x4b, 0x01, 0x02])) + 8); // the encrypted flag
    expect(readZip(z)).toBeNull();
  });
});

describe('rebrandDocument', () => {
  it('replaces the engine brand and ours in every XML part of a Word file, and leaves media alone', () => {
    const r = rebrandDocument('docx', docx(), ['Dev SEO', 'Alaventra'], 'North & Co');
    expect(r).toMatchObject({ rewritable: true, changed: true });
    const e = readZip(r.data)!;
    expect(e.find((x) => x.name === 'word/document.xml')!.data.toString()).toBe('<w:document><w:t>Prepared by North &amp; Co</w:t><w:t>North &amp; Co report</w:t></w:document>');
    expect(e.find((x) => x.name === 'word/footer1.xml')!.data.toString()).toBe('<w:ftr><w:t>North &amp; Co · page 1</w:t></w:ftr>');
    expect([...e.find((x) => x.name === 'word/media/image1.png')!.data]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x44, 0x65, 0x76]);
  });
  it('rewrites text files and refuses the PDF', () => {
    expect(rebrandDocument('md', Buffer.from('# Dev SEO report'), ['Dev SEO'], 'North').data.toString()).toBe('# North report');
    expect(rebrandDocument('html', Buffer.from('<p>Dev SEO</p>'), ['Dev SEO'], 'A&B').data.toString()).toBe('<p>A&amp;B</p>');
    expect(rebrandDocument('pdf', Buffer.from('%PDF'), ['Dev SEO'], 'North')).toMatchObject({ rewritable: false });
    expect(rebrandDocument('other', Buffer.from('<svg/>'), ['Dev SEO'], 'North')).toMatchObject({ rewritable: false });
    expect(rebrandDocument('zip', Buffer.from('broken'), ['Dev SEO'], 'North')).toMatchObject({ rewritable: false });
  });
  it('the fix pack zip has its text files rebranded too', () => {
    const z = writeZip([{ name: 'robots.txt', data: Buffer.from('# generated by Dev SEO\nUser-agent: *') }]);
    expect(readZip(rebrandDocument('zip', z, ['Dev SEO'], 'North').data)![0]!.data.toString()).toBe('# generated by North\nUser-agent: *');
  });
});

describe('portal page shell', () => {
  const html = `<!doctype html><html><head>
    <title>Alaventra</title>
    <meta name="description" content="Enterprise-grade autonomous SEO." />
    <link rel="icon" href="/favicon.ico" sizes="48x48" />
    <link rel="manifest" href="/site.webmanifest" />
    <meta property="og:site_name" content="Alaventra" />
    <meta name="twitter:image" content="/og-image.png" />
    <script src="/theme-init.js"></script>
  </head><body><div id="root"></div></body></html>`;
  it('names the agency and nothing of ours', () => {
    const out = rewriteShell(html, { name: 'North <Insights>', logoUrl: 'https://north.example.com/logo.svg' });
    expect(out).toContain('<title>North &lt;Insights&gt;</title>');
    expect(out).toContain('<meta name="portal-host" content="1" />');
    expect(out).toContain('<link rel="icon" href="https://north.example.com/logo.svg" />');
    expect(out).toContain('<script src="/theme-init.js"></script>');
    expect(out).not.toMatch(/Alaventra|favicon|og:|twitter:|manifest/);
  });
});
