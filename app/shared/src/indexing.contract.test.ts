import { describe, expect, it } from 'vitest';
import fixture from './__fixtures__/index-coverage-techand.json';
import { buildIndexingData, indexingCauseReadings, indexingSitemapReading, indexInSearchLine, INDEX_CAUSES } from './indexing';
import { deriveSiteTasks } from './site-tasks';
import { deliveryDecision, finishedStatus } from './report-delivery';
import { eventsFor } from './integrations';
import type { IndexPageRow, IndexRunRow } from './tables';

// X17 (REVIEW_CROSS.md, fix wave 1): the engine's REAL output fed into the app. `__fixtures__/index-coverage-techand.json` is what the
// engine's harness scenario IX8 writes for techand.ai from real Search Console answers (rows of seo_index_pages, the seo_index_runs row
// and the index_coverage callback), generated by running the engine harness with ONLY_S=^IX in n8nio/n8n:2.41.4. Regenerate it after an
// engine change; a renamed column or code then fails here instead of on a client's page.

const rows = fixture.rows as unknown as Partial<IndexPageRow>[];
const runs = fixture.runs as unknown as Partial<IndexRunRow>[];
const cb = fixture.callback as unknown as Record<string, unknown> & { summary: Record<string, unknown> };
const run = runs[0];

describe('the engine\'s real rows through the app', () => {
  const d = buildIndexingData({ rows, runs, events: [], impacts: [], settings: { on: true, dailyCap: 300 } });

  it('every code the engine wrote is one the app knows (no "Other")', () => {
    for (const r of rows) if (r.cause) expect(INDEX_CAUSES as readonly string[]).toContain(r.cause);
    expect(d.groups.some((g) => g.cause === 'other')).toBe(false);
  });

  it('the page\'s totals equal the engine\'s run row', () => {
    expect(d.status).toBe('ok');
    expect(d.totals.known).toBe(Number(run.known));
    expect(d.totals.indexed).toBe(Number(run.indexed));
    expect(d.totals.unknown).toBe(Number(run.unknown));
    expect(d.lanes.new.known).toBe(Number(run.new_pages));
    expect(d.checkedAt).toBe(run.run_at);
    expect(d.notice).toBeNull();
  });

  it('the groups count what the run counted per cause and per action', () => {
    const byCause: Record<string, number> = JSON.parse(String(run.by_cause_json));
    for (const [cause, n] of Object.entries(byCause)) expect(d.groups.filter((g) => g.cause === cause).reduce((s, g) => s + g.count, 0)).toBe(n);
    const byAction: Record<string, number> = JSON.parse(String(run.by_action_json));
    expect(d.totals.needYou).toBe((byAction.site_fix ?? 0) + (byAction.links ?? 0) + (byAction.duplicate ?? 0) + (byAction.quality ?? 0));
  });

  it('X15: the slim read (in-search pages as the run\'s counts) gives the same page', () => {
    const slim = buildIndexingData({ rows: rows.filter((r) => r.state !== 'indexed' || r.cause === 'indexed_not_in_sitemap'), runs, events: [], impacts: [], settings: { on: true, dailyCap: 300 }, indexedCounts: { all: Number(run.indexed), newLane: Number(run.new_indexed) } });
    expect(slim.totals).toEqual(d.totals);
    expect(slim.groups).toEqual(d.groups);
  });

  it('the steps on the website come from the site-fix rows, and the sitemap reading from sitemaps_json', () => {
    const causes = indexingCauseReadings(rows);
    expect(causes.map((c) => [c.cause, c.total]).sort()).toEqual([['not_found', 3], ['redirect', 5]]);
    const sm = indexingSitemapReading(runs);
    expect(sm).toMatchObject({ submitted: 1, errors: 0 });
    const tasks = deriveSiteTasks({ domain: 'techand.ai', indexnow: null, access: null, reclaim: null, indexing: { runAt: String(run.run_at), causes, sitemap: sm } }, []);
    expect(tasks.map((t) => t.key).sort()).toEqual(['indexing:not_found', 'indexing:redirect']);
  });
});

describe('the engine\'s real callback through the app', () => {
  it('is a finished report that is delivered (status "complete"), with its summary in the DESIGN §5 shape', () => {
    expect(cb.stage).toBe('index_coverage');
    expect(finishedStatus('index_coverage', String(cb.status))).toBe(true);
    expect(deliveryDecision({ stage: 'index_coverage', status: String(cb.status), payload: cb }).deliver).toBe(true);
    for (const k of ['known', 'indexed', 'not_indexed', 'excluded', 'unknown', 'backlog_left', 'new_pages', 'new_indexed', 'by_action', 'by_cause', 'dropped', 'freeze', 'events', 'impact']) expect(cb.summary).toHaveProperty(k);
  });

  it('raises report.ready and no alert when nothing dropped out', () => {
    const ev = eventsFor({ stage: 'index_coverage', status: String(cb.status), payload: cb, report: { id: 'r', title: 'Index coverage', stage: 'index_coverage', status: 'complete', receivedAt: '', scheduled: true, runId: null, websiteId: null, url: '' }, runBefore: null, runAfter: null });
    expect(ev.map((e) => e.type)).toEqual(['report.ready']);
  });

  it('A9: the report\'s headline and the page\'s say the same thing from the same counts', () => {
    const d = buildIndexingData({ rows, runs, events: [], impacts: [], settings: { on: true, dailyCap: 300 } });
    const m = cb.summary;
    const leaveOut = Number((m.by_action as Record<string, number>).leave_out ?? 0);
    const checked = Number(m.indexed) + Number(m.not_indexed) + Number(m.excluded);
    const report = indexInSearchLine({ indexed: Number(m.indexed), shouldBe: checked - leaveOut, known: Number(m.known), notChecked: Number(m.unknown) });
    const page = indexInSearchLine({ indexed: d.totals.indexed, shouldBe: d.totals.shouldBe, known: d.totals.known, notChecked: d.totals.unknown + d.totals.errors });
    expect(report).toBe(page);
  });
});
