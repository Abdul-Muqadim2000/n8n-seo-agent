import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { fitEvidence, fitGate, fitStored, fitTopic, type FitContext, type FitResult } from './fit-gate';

// KW-PARITY (2026-10-21): ONE keyword fit gate. The app's gate (fit-gate.ts -> fit-gate.generated.js, written by build_v4.py) must be the
// engine's kit (n8n/seo-agent/v5/code/_fit_gate.js) and decide every case of the labelled accuracy set
// (n8n/seo-agent/harness/accuracy/keywords.json) exactly as the kit does: the same decision AND the same reason class. The kit is
// evaluated here straight from the engine folder, so a kit change without a rebuild fails this suite. Needs the repo root (CI checks it
// out whole; locally mount the repo root, as the cadence fixture test does).

const here = dirname(fileURLToPath(import.meta.url));
const ENGINE = join(here, '../../../n8n/seo-agent');
const KIT_SRC = readFileSync(join(ENGINE, 'v5/code/_fit_gate.js'), 'utf8').replace(/\n+$/, '');
const GENERATED = readFileSync(join(here, 'fit-gate.generated.js'), 'utf8');

type Gate = (keyword: string, ctx?: FitContext) => FitResult;
const KIT = new Function(KIT_SRC + '\nreturn { fitGate, fitStored, fitTopic, fitEvidence };')() as {
  fitGate: Gate;
  fitStored: typeof fitStored;
  fitTopic: typeof fitTopic;
  fitEvidence: typeof fitEvidence;
};

interface Site {
  site: string;
  own_domain: string;
  services?: string[];
  business?: string;
  competitors?: string[];
  serp_domains?: string[];
  brands?: Record<string, string>;
}
interface Case {
  id: string;
  site: string;
  keyword: string;
  label: 'in' | 'out';
  expect: string;
  intent?: string;
  serp?: { top_domains?: string[]; paa?: string[] };
}
const SET = JSON.parse(readFileSync(join(ENGINE, 'harness/accuracy/keywords.json'), 'utf8')) as { sites: Site[]; cases: Case[] };

// the context per site exactly as the engine's scorer builds it (harness/accuracy/score_keywords.js kitCtx), and its reason classes
const kitCtx = (site: Site, c: Case): FitContext => {
  const s = c.serp || null;
  const ctx: FitContext = {
    own_domain: site.own_domain,
    competitors: site.competitors || [],
    serp_domains: [...(site.serp_domains || [])],
    brands: site.brands || {},
    protect: [...(site.services || []), String(site.business || '').slice(0, 400)],
    topics: [...(site.services || []), String(site.business || '').slice(0, 600)],
    topic_label: 'what this website sells',
    intent: c.intent || '',
  };
  if (s) {
    ctx.serp = s.top_domains || [];
    ctx.serp_domains = [...new Set([...(ctx.serp_domains || []), ...(s.top_domains || []).filter((d) => d !== site.own_domain)])];
    ctx.career = { pages: (s.top_domains || []).map((d) => ({ domain: d, url: '', title: '' })), paa: s.paa || [], related: [] };
  }
  return ctx;
};
const CLASS_OF: Record<string, string> = {
  'other brand': 'other_brand',
  'own brand': 'navigational',
  navigational: 'navigational',
  portal: 'navigational',
  government: 'government',
  'job search': 'career',
  'off topic': 'off_topic',
  'too broad': 'too_broad',
  empty: 'empty',
};
const classOf = (g: FitResult) => (g.ok === false ? CLASS_OF[String(g.reason)] || String(g.reason || 'none') : 'in_topic');

describe('KW-PARITY: the app decides keywords with the engine\'s own fit gate', () => {
  it('the generated module is the current kit, byte for byte (rebuild with python3 build_v4.py when this fails)', () => {
    expect(GENERATED.includes(KIT_SRC + '\n\nexport {')).toBe(true);
    expect(GENERATED.startsWith('// GENERATED by n8n/seo-agent/build_v4.py from v5/code/_fit_gate.js, do not edit by hand.')).toBe(true);
  });

  it('the labelled set is there to compare on (every site has cases)', () => {
    expect(SET.cases.length).toBeGreaterThanOrEqual(80);
    expect(SET.sites.every((s) => SET.cases.some((c) => c.site === s.site))).toBe(true);
  });

  it('every case of harness/accuracy/keywords.json: the same decision, the same reason class and the same sentence as the engine kit', () => {
    const diffs: string[] = [];
    for (const site of SET.sites) {
      for (const c of SET.cases.filter((x) => x.site === site.site)) {
        const app = fitGate(c.keyword, kitCtx(site, c));
        const eng = KIT.fitGate(c.keyword, kitCtx(site, c));
        if (app.ok !== eng.ok || classOf(app) !== classOf(eng) || (app.detail || '') !== (eng.detail || ''))
          diffs.push(`${c.id} "${c.keyword}": app ${classOf(app)} / engine ${classOf(eng)}`);
        // the stored-row path and the topic measures use the same code
        const row = { keyword: c.keyword, status: 'planned' };
        expect(fitStored(row, kitCtx(site, c))).toEqual(KIT.fitStored(row, kitCtx(site, c)));
        const topics = kitCtx(site, c).topics;
        expect(fitTopic(c.keyword, topics)).toEqual(KIT.fitTopic(c.keyword, topics));
        expect(fitEvidence(c.keyword, topics, { services: site.services })).toEqual(KIT.fitEvidence(c.keyword, topics, { services: site.services }));
      }
    }
    expect(diffs).toEqual([]);
  });
});
