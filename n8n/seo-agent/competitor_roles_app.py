#!/usr/bin/env python3
"""CR17-F (2026-11-17, client report C5, build section 196): the competitor roles have ONE source, `v5/code/_competitors.js` (CMP).

The engine inlines it (/*__COMPETITORS__*/) wherever a path asks "is this site a competitor?": the Link Builder's gate (through _rivals.js and
the outreach kit), AI visibility (_ai_entities.js, AI Metrics), AI Growth's earned media, the monitors' one competitor list (_monitor_sites.js),
keyword research, the ladder and the full report. The app shows the same roles (AI visibility "Software and platforms AI names", Rankings
"Above you", the Competitors page, Site settings), so `write_app_files()` writes the kit itself, unchanged, as an ES module:

  app/shared/src/competitor-roles.generated.js    the kit's source + one export line
  app/shared/src/competitor-roles.generated.d.ts  the types of what the app uses

`app/shared/src/competitor-roles.parity.test.ts` evaluates `_competitors.js` straight from this folder and fails when the generated file is
stale. Both files are committed, so the app never needs this build.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP_SRC = os.path.normpath(os.path.join(HERE, '..', '..', 'app', 'shared', 'src'))
JS_PATH = os.path.join(APP_SRC, 'competitor-roles.generated.js')
DTS_PATH = os.path.join(APP_SRC, 'competitor-roles.generated.d.ts')

HEADER = ("// GENERATED by n8n/seo-agent/build_v4.py (competitor_roles_app.py) from v5/code/_competitors.js, do not edit by hand.\n"
          "// CR17-F (2026-11-17): the engine's one competitor role classifier, byte for byte, as an ES module for the app (competitor-roles.ts wraps it).\n"
          "// Change the kit and run `python3 build_v4.py`; app/shared/src/competitor-roles.parity.test.ts fails while this file is stale.\n")

DTS = HEADER + """
export type CompetitorRole = 'competitor' | 'listing' | 'also_ranks' | 'authority' | 'software' | 'your_platform' | 'not_competitor' | 'you' | 'unknown';
export type CompetitorLeftOut = 'competitor' | 'competitor_list' | 'listing' | 'your_platform' | 'software';

export interface CompetitorRoleContext {
  own_domain?: string;
  services?: readonly (string | { name?: string; label?: string })[];
  topics?: readonly string[];
  principals?: readonly string[];
  chosen?: readonly string[];
  declared?: readonly string[];
  not_competitors?: readonly string[];
  overrides?: Record<string, 'chosen' | 'not_competitor' | string>;
  ki?: Record<string, string>;
  url?: string;
}

export interface CompetitorRoleResult {
  role: CompetitorRole;
  class: string;
  by: 'user' | 'rule' | 'ki';
  reason: string;
  words: string;
  host: string;
  reg: string;
}

export interface CompetitorOneList {
  list: string[];
  chosen: string[];
  declared: string[];
  removed: string[];
}

export declare const CMP: {
  host(h: string): string;
  reg(h: string): string;
  kindOfHost(domainOrUrl: string, own?: string): string;
  role(host: string, ctx?: CompetitorRoleContext): CompetitorRoleResult;
  isCompetitor(host: string, ctx?: CompetitorRoleContext): boolean;
  oneList(o: { declared?: readonly string[] | string; ki_rows?: readonly { comp_domain: string; status?: string; status_by?: string; site_id?: string }[]; not_competitors?: readonly string[] | string; own_domain?: string; site_id?: string; max?: number }): CompetitorOneList;
  partnerDirectory(url: string): boolean;
  listPage(title: string, url: string): boolean;
  principalHosts(ctx?: CompetitorRoleContext): string[];
  ROLES: CompetitorRole[];
  ROLE_WORDS: Record<CompetitorRole, string>;
  LEFT_OUT: Record<CompetitorLeftOut, string>;
  KI_ROLE: Record<string, CompetitorRole>;
};
"""


def _write(path, text):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)


def write_app_files(kit_src):
    """The kit (as the build inlines it) -> the app's generated module + its types. Returns the two paths."""
    src = kit_src.rstrip('\n')
    assert '/*__' not in src, '_competitors.js: a placeholder in the kit would reach the app unexpanded'
    assert not re.search(r'\$\(|\$input|\$json|\brequire\(', src), '_competitors.js: the kit reads n8n or Node globals, so it cannot run in the app as is'
    assert re.search(r'^const CMP = \(\(\) => \{', src, re.M), '_competitors.js no longer defines CMP at top level'
    for banned in ('structuredClone(', 'Object.defineProperty(', 'Object.defineProperties(', 'Object.setPrototypeOf(', 'new URL('):
        assert banned not in src, '_competitors.js uses %s, which the n8n Code sandbox does not run (memory note 2026-10-25)' % banned
    if os.path.isdir(APP_SRC):
        _write(JS_PATH, HEADER + src + '\n\nexport { CMP };\n')
        _write(DTS_PATH, DTS)
    return JS_PATH, DTS_PATH


if __name__ == '__main__':
    print(write_app_files(open(os.path.join(HERE, 'v5', 'code', '_competitors.js'), encoding='utf-8').read()))
