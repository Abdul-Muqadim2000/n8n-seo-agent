#!/usr/bin/env python3
"""G12 / G29 (2026-10-13, system review FIX_PLAN.md): the dated event registry and the three reporting kits, inlined by every builder
through one helper so the engine and the web app mark the same dates and use the same words.

The registry is `v5/data/seo_events.json` — THE one place to add a Google update or a data break. From it this module feeds:

  /*__SEO_EVENTS__*/      the whole registry as a JS object literal (v5/code/_annotations.js)
  /*__GOOGLE_UPDATES__*/  just the google_updates array (v5/code/_site_stats.js, the alert context of G28)
  /*__LINEAGE__*/         v5/code/_lineage.js      — source / period / sample / basis on every number (G29)
  /*__ANNOTATIONS__*/     v5/code/_annotations.js  — event marks for the charts and the reports (G12), registry already inlined
  /*__CHANGE_TEST__*/     v5/code/_change_test.js  — the control-group comparison and its graded verdicts (G12)

`write_app_ts()` writes the same registry as `app/shared/src/seo-events.generated.ts` (committed, so the app never needs this build).
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
V5 = next(p for p in [os.path.join(HERE, 'v5'), os.path.join(HERE, '..', 'v5')] if os.path.isdir(p))
EVENTS_PATH = os.path.join(V5, 'data', 'seo_events.json')
APP_TS_PATH = os.path.normpath(os.path.join(HERE, '..', '..', 'app', 'shared', 'src', 'seo-events.generated.ts'))

EVENTS = json.load(open(EVENTS_PATH, encoding='utf-8'))
GOOGLE_UPDATES = EVENTS.get('google_updates') or []
DATA_BREAKS = EVENTS.get('data_breaks') or []
assert GOOGLE_UPDATES and DATA_BREAKS, EVENTS_PATH + ': the registry needs at least one Google update and one data break'
_DAY = re.compile(r'^\d{4}-\d{2}-\d{2}$')
for _e in GOOGLE_UPDATES + DATA_BREAKS:
    assert _e.get('name'), EVENTS_PATH + ': every event needs a name'
    assert _DAY.match(str(_e.get('start', ''))) and _DAY.match(str(_e.get('end', ''))), '%s: %s needs start and end as YYYY-MM-DD' % (EVENTS_PATH, _e.get('name'))
    assert str(_e['start']) <= str(_e['end']), '%s: %s ends before it starts' % (EVENTS_PATH, _e['name'])
for _b in DATA_BREAKS:
    assert _b.get('detail'), EVENTS_PATH + ': a data break must say what it did to the numbers (detail)'

_REGISTRY = {'updated': EVENTS.get('updated', ''), 'google_updates': GOOGLE_UPDATES, 'data_breaks': DATA_BREAKS}
EVENTS_JS = json.dumps(_REGISTRY, ensure_ascii=False)
GOOGLE_UPDATES_JS = json.dumps(GOOGLE_UPDATES, ensure_ascii=False)

_rd = lambda p: open(os.path.join(V5, 'code', p), encoding='utf-8').read().rstrip('\n')
LINEAGE_SRC = _rd('_lineage.js')
ANNOTATIONS_SRC = _rd('_annotations.js').replace('/*__SEO_EVENTS__*/', EVENTS_JS)
CHANGE_TEST_SRC = _rd('_change_test.js')
assert '/*__' not in ANNOTATIONS_SRC, '_annotations.js: placeholder left'


def inline(s):
    """Every G12 / G29 marker in one Code-node source."""
    return (s.replace('/*__ANNOTATIONS__*/', ANNOTATIONS_SRC)
             .replace('/*__LINEAGE__*/', LINEAGE_SRC)
             .replace('/*__CHANGE_TEST__*/', CHANGE_TEST_SRC)
             .replace('/*__GOOGLE_UPDATES__*/', GOOGLE_UPDATES_JS)
             .replace('/*__SEO_EVENTS__*/', EVENTS_JS))


def write_app_ts(path=None):
    """The same registry for the app's charts (generated, committed; the app's own tests check it against this file)."""
    p = path or APP_TS_PATH
    body = (
        "// GENERATED by n8n/seo-agent/build_v4.py from n8n/seo-agent/v5/data/seo_events.json, do not edit by hand.\n"
        "// G12 (2026-10-13, system review FIX_PLAN.md): the dated events the charts mark. Add a Google update or a data break to\n"
        "// that JSON file and run `python3 build_v4.py`; the engine (v5/code/_annotations.js, _site_stats.js) and this file stay in step.\n"
        "export interface SeoEvent {\n  name: string;\n  /** first day of the rollout (YYYY-MM-DD) */\n  start: string;\n  /** last day of the rollout (YYYY-MM-DD) */\n  end: string;\n"
        "  /** a data break: what it did to the numbers */\n  detail?: string;\n  /** a data break: which measures it moved */\n  affects?: readonly string[];\n}\n\n"
        "export const SEO_EVENTS: { updated: string; googleUpdates: readonly SeoEvent[]; dataBreaks: readonly SeoEvent[] } = "
        + json.dumps({'updated': _REGISTRY['updated'], 'googleUpdates': GOOGLE_UPDATES, 'dataBreaks': DATA_BREAKS}, ensure_ascii=False, indent=2)
        + ";\n")
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else ''
    if old != body:
        open(p, 'w', encoding='utf-8').write(body)
    return p
