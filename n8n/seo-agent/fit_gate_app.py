#!/usr/bin/env python3
"""KW-PARITY (2026-10-21): the keyword fit gate has ONE source, `v5/code/_fit_gate.js`.

The engine inlines it into every keyword node (the /*__FIT_GATE__*/ placeholder). The web app used to carry a hand-written port
(`app/shared/src/fit-gate.ts`), which fell behind the kit the day the kit was redesigned (KW-GATE), so the app's cadence mirror and the
engine could decide the same keyword differently. `write_app_files()` writes the kit itself, unchanged, as an ES module the app imports:

  app/shared/src/fit-gate.generated.js    the kit's source + one export line
  app/shared/src/fit-gate.generated.d.ts  the types of what the app uses

`app/shared/src/fit-gate.ts` is a thin typed wrapper over them; `fit-gate.parity.test.ts` evaluates `_fit_gate.js` straight from this
folder and fails when the generated file is stale or decides any case of `harness/accuracy/keywords.json` differently. Both files are
committed (like `seo-events.generated.ts`), so the app never needs this build.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP_SRC = os.path.normpath(os.path.join(HERE, '..', '..', 'app', 'shared', 'src'))
JS_PATH = os.path.join(APP_SRC, 'fit-gate.generated.js')
DTS_PATH = os.path.join(APP_SRC, 'fit-gate.generated.d.ts')

# what the module exports: every name must be a top-level `const NAME =` or `function NAME(` of the kit
EXPORTS = ['fitGate', 'fitTopic', 'fitEvidence', 'fitStored', 'fitStoredLive', 'fitTokens', 'fitHost', 'fitLabels', 'fitOwnLabels',
           'fitLearnedBrands', 'fitBrandList', 'FITR']

HEADER = ("// GENERATED by n8n/seo-agent/build_v4.py from v5/code/_fit_gate.js, do not edit by hand.\n"
          "// KW-PARITY (2026-10-21): the engine's keyword fit gate, byte for byte, as an ES module for the app (fit-gate.ts wraps it with types).\n"
          "// Change the kit and run `python3 build_v4.py`; app/shared/src/fit-gate.parity.test.ts fails while this file is stale.\n")

DTS = HEADER + """
export type FitReason = 'own brand' | 'navigational' | 'government' | 'portal' | 'job search' | 'other brand' | 'off topic' | 'too broad' | 'empty';

export interface FitResult {
  ok: boolean;
  reason?: FitReason | string;
  detail?: string;
  /** a job search read from the results page: the evidence */
  career?: unknown;
}

export interface FitCareerInput {
  /** the keyword's organic results: domain, url, title */
  pages?: { domain?: string; url?: string; title?: string }[];
  /** people-also-ask questions */
  paa?: string[];
  /** related searches */
  related?: string[];
  topics?: string[] | string | null;
}

export interface FitContext {
  intent?: string;
  own_domain?: string;
  /** domains the website declared as competitors */
  competitors?: string[];
  /** domains on the keyword's results page (or the ladder's) */
  serp_domains?: string[];
  /** this keyword's own top domains, in rank order */
  serp?: string[];
  /** brand name -> domain, learned from AI answers */
  brands?: Record<string, string>;
  /** words of the head terms / services that never count as a brand */
  protect?: string[];
  /** the services the client DECLARED (never the crawl's guesses) */
  services?: string[] | string;
  /** the client's own brand names */
  brand_names?: string[];
  /** what the website sells and the keywords chosen: with them, off topic and too broad are judged */
  topics?: string[] | string | null;
  topic_label?: string;
  topic_bar?: number;
  topic_min_words?: number;
  /** the keyword's results page, for the job / course search rule */
  career?: FitCareerInput;
  /** G19 hook, called last */
  relevance?: (keyword: string) => { ok?: boolean; reason?: string; detail?: string } | null | undefined;
  /** fitStored: the row's page is already written */
  written?: boolean;
}

export interface TopicResult {
  ok: boolean;
  reason: '' | 'off topic' | 'too broad';
  detail: string;
  /** null when nothing was judged (too few topic words on file) */
  share: number | null;
}

export interface TopicEvidence {
  /** in: the keyword's own words are in the topics given; out: with 12+ topic words on file it misses the bar; unknown: too little on file */
  verdict: 'in' | 'out' | 'unknown';
  share: number | null;
  words: number;
  detail: string;
  basis?: 'topics' | 'declared service';
  anchors?: string[];
}

export interface StoredFit {
  ok: boolean;
  live: boolean;
  flagged: boolean;
  reason: string;
  detail: string;
  note: string;
}

export interface FitSetAside {
  keyword: string;
  reason: string;
  detail: string;
  note: string;
  written: boolean;
  dropped: boolean;
  where: string;
  ladder_id: string;
  head_keyword: string;
  rung: number;
  page_no: number;
  status: string;
  target_url: string;
  prompt_id: string;
}

export declare function fitGate(keyword: string, ctx?: FitContext): FitResult;
export declare function fitTopic(keyword: string, topics: string[] | string | null | undefined, ctx?: FitContext): TopicResult;
export declare function fitEvidence(keyword: string, topics: string[] | string | null | undefined, ctx?: FitContext): TopicEvidence;
export declare const fitStored: (row: Record<string, unknown>, ctx?: FitContext) => StoredFit;
export declare const fitStoredLive: (row: Record<string, unknown>) => boolean;
export declare const fitTokens: (s: unknown) => string[];
export declare const fitHost: (d: unknown) => string;
export declare const fitLabels: (domain: unknown, protect?: string[]) => string[];
export declare const fitOwnLabels: (domain: unknown, toks?: string[], protect?: string[]) => string[];
export declare const fitLearnedBrands: (rows: unknown[]) => Record<string, string>;
export declare const fitBrandList: (ctx: FitContext, protect?: string[]) => string;
export declare const FITR: {
  ctx(o?: Record<string, unknown>): FitContext;
  rungs<T>(rows: T[], ctx?: FitContext, opts?: { keyword?: (row: T) => unknown; live?: (row: T) => boolean; serpFor?: (keyword: string, row: T) => string[] | null | undefined; where?: string }): {
    keep: T[]; set_aside: FitSetAside[]; dropped: FitSetAside[]; flagged: FitSetAside[]; refused_keywords: string[];
  };
  line(set_aside: FitSetAside[], what?: string): string;
};
"""


def _write(p, body):
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else ''
    if old != body:
        open(p, 'w', encoding='utf-8').write(body)


def write_app_files(fit_gate_src):
    """The kit (as the build inlines it) -> the app's generated module + its types. Returns the two paths."""
    src = fit_gate_src.rstrip('\n')
    assert '/*__' not in src, '_fit_gate.js: a placeholder in the kit would reach the app unexpanded'
    assert not re.search(r'\$\(|\$input|\$json|\brequire\(', src), '_fit_gate.js: the kit reads n8n or Node globals, so it cannot run in the app as is'
    for name in EXPORTS:
        assert re.search(r'^(const %s = |function %s\()' % (re.escape(name), re.escape(name)), src, re.M), \
            'KW-PARITY: _fit_gate.js no longer defines %s at top level; update fit_gate_app.EXPORTS and the .d.ts' % name
    _write(JS_PATH, HEADER + src + '\n\nexport { ' + ', '.join(EXPORTS) + ' };\n')
    _write(DTS_PATH, DTS)
    return JS_PATH, DTS_PATH
