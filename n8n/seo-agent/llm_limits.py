"""LLM-LIMITS (2026-10-27): one table of output limits for every Claude node of every generated workflow, and the lint that holds them.

Why (production, 2026-10-25, techand.ai, execution 2195): the Editor (Claude Opus 5.5, adaptive thinking, effort medium,
maxTokensToSample 32768) returned 749 words that end mid-word ("Does the add-on cover gratu"). With thinking on, the thinking
tokens and the visible answer share ONE max_tokens ceiling; Opus 5.5 rejects a fixed thinking budget (`budget_tokens` is a 400 on
Opus 5.5 / Sonnet 5.5, adaptive thinking with an effort level is the only setting), so nothing stopped the model from spending
almost all of the 32,768 on thinking. The API then ends the stream with stop_reason "max_tokens", and n8n 2.41.4 hands the cut text
on as a success: @langchain/anthropic 1.5.6's streaming `_generate` returns only `{ text, message }` (the stop reason rides in the
message's additional_kwargs) and the n8n agent node outputs only `{ output }`. The full evidence is in
docs/llm-limits-2026-10-27/LIMITS.md.

The rule (owner, 2026-10-27): the best page matters, token cost does not. Thinking is never reduced; the ceiling is raised so the
thinking AND the whole output always fit:
  * every node is declared here (an undeclared Claude node fails the build), with
      think   - the thinking it may use (the planning budget; the API takes no number on these models, so it is enforced by the room
                the ceiling leaves, not by a parameter). Generous: at least what the node uses today.
      head    - the room its own output needs: the longest page / brief / e-mail / JSON it writes, with overhead and a safety margin.
      max     - maxTokensToSample. The lint requires max >= think + head, and max <= the model's documented maximum output.
  * a node whose max is above the SDK's non-streaming limit (@anthropic-ai/sdk 0.115.0 refuses a non-streaming request whose
    max_tokens implies more than 10 minutes: 60 * 60 * max / 128000 > 600, i.e. max > 21,333) streams.
  * a node with no thinking has think 0 and still needs max >= head.
  * `cost_think` is what the cost kit (v5/code/_cost_cal.js) models as the thinking of one call: 'seen' = the measured THINK_SEEN
    figure of a non-streaming call, a number = the effort budget it was priced at before this change. Raising the ceiling does not
    change a single price: the ceiling is room, not spend.
Never lower a think budget to pass the lint: raise max instead.
"""
