def _write(path, text):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)


def write_app_files(kit_src):
    """The kit (as the build inlines it) -> the app's generated module + its types. Returns the two paths."""
    src = kit_src.rstrip('\n')
    assert '/*__' not in src, '_ai_focus.js: a placeholder in the kit would reach the app unexpanded'
    assert not re.search(r'\$\(|\$input|\$json|\brequire\(', src), '_ai_focus.js: the kit reads n8n or Node globals, so it cannot run in the app as is'
    assert re.search(r'^const AIF = \(\(\) => \{', src, re.M), '_ai_focus.js no longer defines AIF at top level'
    for banned in ('structuredClone(', 'Object.defineProperty(', 'Object.defineProperties(', 'Object.setPrototypeOf(', 'new URL('):
        assert banned not in src, '_ai_focus.js uses %s, which the n8n Code sandbox does not run (memory note 2026-10-25)' % banned
    _write(JS_PATH, HEADER + src + '\n\nexport { AIF };\n')
    _write(DTS_PATH, DTS)
    return JS_PATH, DTS_PATH


